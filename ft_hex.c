#include "ft_printf.h"

int	ft_hex(int n)
{
	char *base;
	base = "0123456789abcdef";
	if (n > 16)
		ft_putnbr_type(n / 16, 1, 0);
	ft_putchar_fd((n % 16) + base[n], 0);
}